import { expect, test, type Page } from '@playwright/test';
import { PRESETS } from '../../src/domain/config';
import { PATTERN_LABELS, sensorConditions } from '../../src/domain/conditions';
import { auditWorker, assertAccessible, assertNoAnswerLeak, finalRecord, lastView } from './workerHarness';

for (const id of ['urban-dusk', 'night-watch', 'rural-crossing']) {
  const preset = PRESETS.find(p => p.id === id)!;
  test(`${preset.name}: real distinct conditions, request provenance and full offline completion`, async ({ page, context }, testInfo) => {
    test.setTimeout(120000);
    const errors: string[] = [];
    page.on('pageerror', e => errors.push(e.message));
    page.on('console', e => { if (e.type() === 'error') errors.push(e.text()); });
    await auditWorker(page); await page.goto('/#/lab');
    await page.getByRole('button', { name: new RegExp(`^${preset.name}`) }).click();
    await expect(page.getByLabel('Traffic pattern')).toHaveValue(preset.config.trafficPattern);
    const settings = sensorConditions(preset.config);
    const card = page.getByRole('region', { name: 'Synthetic sensor model settings' });
    await expect(card).toContainText(PATTERN_LABELS[preset.config.trafficPattern]);
    await expect(card).toContainText(String(Math.round(settings.returnSetting * 100)));
    await page.getByRole('button', { name: 'Review briefing', exact: true }).click();
    await expect(page.getByText('Local worker ready', { exact: true })).toBeVisible();
    await page.getByText('How conditions affect evidence', { exact: true }).click();
    await assertAccessible(page, `${preset.name} expanded condition briefing`);
    await page.waitForLoadState('networkidle'); await context.setOffline(true);
    await page.getByRole('button', { name: 'Start exercise', exact: true }).click();
    await page.getByLabel('Clock', { exact: true }).selectOption('4');
    const map = page.getByTestId('observation-map');
    await expect(map).toHaveAttribute('data-pattern', preset.config.trafficPattern);
    await expect(map).toHaveClass(new RegExp(`observation-map--${preset.config.lighting}`));
    await expect(map).toHaveAttribute('data-weather', preset.config.weather);
    if (preset.config.environment === 'urban') await expect(page.getByTestId('clutter-zones')).toBeVisible();
    else await expect(page.getByTestId('clutter-zones')).toHaveCount(0);
    if (preset.config.weather === 'rain') await expect(page.getByTestId('rain-layer')).toBeVisible();
    const queue = page.locator('.track-queue-items > button');
    await expect(queue.first()).toBeVisible({ timeout: 20000 });
    const trackId = (await queue.first().getAttribute('aria-label'))!.match(/T\d{2}/)![0];
    await queue.first().click();
    await page.getByRole('button', { name: 'Mark as tracked', exact: true }).click();
    await page.getByRole('button', { name: 'Request observation', exact: true }).click();
    await expect(page.getByRole('button', { name: /Request cooldown/ })).toBeDisabled();
    const requestedView = (await lastView(page))!;
    const request = requestedView.events.slice().reverse().find(e => e.type === 'action' && e.data.action.kind === 'request_observation')!;
    await expect(page.getByTestId('request-evidence-status')).toContainText(/queued|delivered|Delay or dropout/);
    await expect.poll(async () => (await lastView(page))?.elapsedSeconds ?? 0, { timeout: 15000 }).toBeGreaterThanOrEqual(request.time + 2 + settings.maximumDelay + 2);
    const afterRequest = (await lastView(page))!.tracks.find(t => t.id === trackId)!;
    const actualRequested = afterRequest.observations.find(o => o.source === 'requested' && o.capturedAt === request.time + 2);
    if (actualRequested) await expect(page.getByTestId('request-evidence-status')).toContainText('Requested capture delivered');
    else await expect(page.getByTestId('request-evidence-status')).toContainText('No return from the latest request');
    await page.getByRole('button', { name: 'Unknown / insufficient evidence', exact: true }).click();
    await page.getByRole('button', { name: 'Record assessment', exact: true }).click();
    await page.getByLabel('Observation summary', { exact: true }).fill('The actual delivered evidence is intermittent. Keep this synthetic assessment uncertain and continue observation.');
    await page.getByRole('button', { name: 'Submit report', exact: true }).click();
    await expect(queue).toHaveCount(preset.config.trackCount, { timeout: 25000 });
    await page.getByLabel('Clock', { exact: true }).selectOption('1');
    await page.getByRole('button', { name: 'Pause', exact: true }).click();
    const paused = (await lastView(page))!;
    const observations = paused.events.filter(e => e.type === 'observation').map(e => e.data.observation);
    await expect(page.getByTestId('feed-delivered')).toHaveText(String(observations.length));
    await expect(page.getByTestId('feed-delay')).toHaveText(`${(observations.reduce((sum, o) => sum + o.deliveredAt - o.capturedAt, 0) / observations.length).toFixed(1)}s`);
    const stale = paused.tracks.filter(t => paused.elapsedSeconds - t.latest.capturedAt > 10).length;
    await expect(page.getByTestId('feed-stale')).toHaveText(`${stale} / ${paused.tracks.length}`);
    const selected = paused.tracks.find(t => t.id === trackId)!;
    await expect(page.getByTestId(`track-marker-${trackId}`)).toHaveAttribute('data-captured-at', String(Math.max(...selected.observations.map(o => o.capturedAt))));
    await page.getByText(/^Delivered evidence/).click();
    await expect(page.getByRole('region', { name: `Delivered evidence for ${trackId}` })).toBeVisible();
    await assertNoAnswerLeak(page); await assertAccessible(page, `${preset.name} expanded delivered evidence`);
    expect(await page.locator('.main-content').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
    await page.getByRole('button', { name: 'Resume', exact: true }).click();
    await page.locator('.main-content').evaluate(el => el.scrollTo(0, 0));
    await page.screenshot({ path: `docs/screenshots/phase6-${id}-${testInfo.project.name}.png`, animations: 'disabled' });
    await page.getByLabel('Clock', { exact: true }).selectOption('4');
    await expect(page.getByTestId('exercise-result')).toBeVisible({ timeout: 40000 });
    const record = await finalRecord(page);
    expect(record.status).toBe('completed'); expect(record.elapsedSeconds).toBe(preset.config.durationSeconds);
    expect(record.schemaVersion).toBe(3); expect(record.scenario.generatorVersion).toBe('generator-2'); expect(record.scenario.sensorVersion).toBe('sensor-2');
    expect(record.scenario.config).toEqual(preset.config);
    const delivered = record.events.filter(e => e.type === 'observation').map(e => e.data.observation);
    expect(new Set(delivered.map(o => o.trackId)).size).toBe(preset.config.trackCount);
    expect(delivered.some(o => o.motion === 'unresolved')).toBe(true);
    expect(delivered.some(o => o.deliveredAt - o.capturedAt > preset.config.delaySeconds)).toBe(true);
    await expect(page.getByTestId('final-score')).toHaveText(record.evaluation.score.toFixed(1));
    for (const metric of record.evaluation.metrics) await expect(page.getByTestId(`metric-${metric.key}`)).toContainText(metric.score.toFixed(1));
    expect(await page.locator('.event-row[data-event-id]').evaluateAll(rows => rows.map(row => row.getAttribute('data-event-id')))).toEqual(record.events.map(e => e.id));
    await expect(page.locator('.review-provenance')).toContainText('generator-2 · sensor-2 · rubric-1');
    await assertAccessible(page, `${preset.name} actual completed result`);
    await page.locator('.main-content').evaluate(el => el.scrollTo(0, 0));
    await page.screenshot({ path: `docs/screenshots/phase6-${id}-result-${testInfo.project.name}.png`, animations: 'disabled' });
    expect(errors).toEqual([]);
  });
}

async function firstCaptures(page: Page) {
  await page.getByRole('button', { name: 'Start exercise', exact: true }).click();
  await page.getByLabel('Clock', { exact: true }).selectOption('4');
  await expect.poll(async () => (await lastView(page))?.elapsedSeconds ?? 0).toBeGreaterThanOrEqual(7);
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  const view = (await lastView(page))!;
  const observations = view.tracks.flatMap(t => t.observations).filter(o => o.capturedAt <= 5).sort((a,b) => a.id.localeCompare(b.id));
  expect(observations.length).toBeGreaterThanOrEqual(4);
  return { view, observations };
}

test('validated grouped configuration reproduces real seeded captures on reset; next seed changes the evidence', async ({ page }) => {
  test.setTimeout(90000); await auditWorker(page); await page.goto('/#/lab');
  await page.getByLabel('Traffic pattern').selectOption('grouped');
  await page.getByRole('button', { name: 'Review briefing', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('at least 3 tracks');
  await page.getByLabel('Synthetic tracks').fill('3');
  await page.getByRole('slider', { name: /Sensor reliability/ }).press('End');
  await expect(page.getByRole('slider', { name: /Sensor reliability/ })).toHaveValue('100');
  await page.getByLabel('Observation noise', { exact: true }).selectOption('0.02');
  await page.getByLabel('Observation delay (seconds)').fill('0');
  await page.getByRole('button', { name: 'Review briefing', exact: true }).click();
  await expect(page.getByText('Local worker ready', { exact: true })).toBeVisible();
  const a = await firstCaptures(page);
  await page.getByRole('button', { name: 'Reset exercise', exact: true }).click();
  await page.getByRole('button', { name: 'Discard & reset', exact: true }).click();
  const b = await firstCaptures(page);
  expect(b.view.sessionId).not.toBe(a.view.sessionId); expect(b.view.scenario.id).toBe(a.view.scenario.id); expect(b.observations).toEqual(a.observations);
  await page.getByRole('button', { name: 'Reset exercise', exact: true }).click();
  await page.getByRole('button', { name: 'Discard & reset', exact: true }).click();
  await page.getByRole('button', { name: 'Edit configuration', exact: true }).click();
  await page.getByRole('button', { name: 'Use next seed', exact: true }).click();
  await expect(page.getByLabel('Random seed', { exact: true })).toHaveValue(String(a.view.scenario.seed + 7919));
  await page.getByRole('button', { name: 'Review briefing', exact: true }).click();
  const c = await firstCaptures(page);
  expect(c.view.scenario.id).not.toBe(a.view.scenario.id); expect(c.observations).not.toEqual(a.observations);
  await assertNoAnswerLeak(page);
  await page.getByRole('button', { name: 'End early', exact: true }).click();
  await page.getByRole('button', { name: 'End & review partial result', exact: true }).click();
  await expect(page.getByText('Partial · aborted', { exact: true })).toBeVisible();
});
