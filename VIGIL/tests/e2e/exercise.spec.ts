import { expect, test } from '@playwright/test';
import { auditWorker, lastView, finalRecord, prepare, start, navigate, assertNoAnswerLeak, assertAccessible } from './workerHarness';

test('real offline exercise: moving evidence, decisions, degraded feed, pause and a log-matched result', async ({ page, context }, testInfo) => {
  test.setTimeout(90000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await auditWorker(page); await prepare(page, null);
  await page.waitForLoadState('networkidle');
  // All required local code is already loaded. Disable the browser network, not just paid APIs.
  await context.setOffline(true);
  await page.getByRole('button', { name: 'Start exercise', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Select track T01', exact: true })).toBeVisible({ timeout: 10000 });
  await page.getByRole('button', { name: 'Select track T01', exact: true }).click();
  await page.getByRole('button', { name: 'Mark as tracked', exact: true }).click();
  const marker = page.getByTestId('track-marker-T01');
  const firstX = await marker.getAttribute('data-observed-x');
  const firstDelivery = await marker.getAttribute('data-delivered-at');
  await expect(marker).not.toHaveAttribute('data-delivered-at', firstDelivery!, { timeout: 10000 });
  expect(await marker.getAttribute('data-observed-x')).not.toBe(firstX);
  const current = await lastView(page);
  expect(Number(await marker.getAttribute('data-observed-x'))).toBe(current!.tracks[0].latest.x);
  await page.getByRole('button', { name: 'Unknown / insufficient evidence', exact: true }).click();
  await page.getByRole('button', { name: 'Record assessment', exact: true }).click();
  await expect(page.getByText(/Recorded: Unknown/)).toBeVisible();
  await page.getByLabel('Observation summary', { exact: true }).fill('The delivered returns are synthetic; classification remains uncertain. Continue observation.');
  await page.getByRole('button', { name: 'Submit report', exact: true }).click();
  await expect(page.getByText('Report recorded · Continue observation', { exact: true })).toBeVisible();
  await page.getByLabel('Clock', { exact: true }).selectOption('4');
  await expect(page.getByText('Synthetic link disruption', { exact: true })).toBeVisible({ timeout: 10000 });
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  await expect(page.getByText('Exercise paused', { exact: true })).toBeVisible();
  const pausedTime = await page.getByTestId('simulation-timer').textContent();
  const pausedEvents = (await lastView(page))!.events.length;
  await page.waitForTimeout(1200); // Intentional wall-clock pause verification, not a simulation shortcut.
  await expect(page.getByTestId('simulation-timer')).toHaveText(pausedTime!);
  expect((await lastView(page))!.events.length).toBe(pausedEvents);
  await expect(page.getByLabel('Active trainee profile')).toBeDisabled();
  await assertNoAnswerLeak(page);
  expect(await page.locator('.main-content').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await assertAccessible(page, 'paused degraded console');
  await page.locator('.main-content').evaluate(el => el.scrollTo(0,0));
  await page.screenshot({ path: `docs/screenshots/phase6-console-${testInfo.project.name}.png`, animations: 'disabled' });
  await page.getByRole('button', { name: 'Resume', exact: true }).click();
  await expect(page.getByTestId('exercise-result')).toBeVisible({ timeout: 30000 });
  const record = await finalRecord(page);
  expect(record.status).toBe('completed'); expect(record.elapsedSeconds).toBe(90); expect(record.evaluation.comparable).toBe(true);
  expect(record.events.at(-1)).toMatchObject({ type: 'finished', data: { outcome: 'completed' } });
  expect(record.events.some(e => e.type === 'sensor_change' && e.data.health === 'degraded')).toBe(true);
  expect(record.events.some(e => e.type === 'paused')).toBe(true);
  const deliveries = record.events.filter(e => e.type === 'observation').map(e => e.data.observation);
  expect(deliveries.some(o => o.confidence < 60) || deliveries.some((o, i) => i > 0 && o.deliveredAt - deliveries[i - 1].deliveredAt >= 10)).toBe(true);
  await expect(page.getByTestId('final-score')).toHaveText(record.evaluation.score.toFixed(1));
  await expect(page.getByTestId('observation-count')).toHaveText(String(record.events.filter(e => e.type === 'observation').length));
  await expect(page.getByTestId('action-count')).toHaveText(String(record.events.filter(e => e.type === 'action').length));
  await expect(page.getByTestId('report-count')).toHaveText('1');
  await expect(page.getByTestId('score-formula')).toContainText(`${record.evaluation.weightedScore.toFixed(1)} weighted credit`);
  for (const metric of record.evaluation.metrics) await expect(page.getByTestId(`metric-${metric.key}`)).toContainText(metric.score.toFixed(1));
  for (const finding of record.evaluation.findings) expect(finding.eventIds.every(id => record.events.some(e => e.id === id))).toBe(true);
  const rows = page.locator('.event-row[data-event-id]');
  await expect(rows).toHaveCount(record.events.length);
  expect(await rows.evaluateAll(elements => elements.map(el => el.getAttribute('data-event-id')))).toEqual(record.events.map(e => e.id));
  await page.getByRole('button', { name: 'Your actions', exact: true }).click();
  await expect(rows).toHaveCount(record.events.filter(e => e.type === 'action').length);
  await page.getByRole('button', { name: 'All events', exact: true }).click();
  await expect(page.getByTestId('outcome-T01')).toContainText('Unknown / insufficient evidence');
  expect(await page.locator('.main-content').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await assertAccessible(page, 'completed baseline result');
  await page.locator('.main-content').evaluate(el => el.scrollTo(0,0));
  await page.screenshot({ path: `docs/screenshots/phase6-result-${testInfo.project.name}.png`, animations: 'disabled' });
  await navigate(page, 'Overview');
  await expect(page.locator('.stat-value').first()).toHaveText('1sessions');
  await expect(page.getByRole('region', { name: 'Recorded exercise results' })).toContainText(record.evaluation.score.toFixed(1));
  expect(errors).toEqual([]);
});

test('keyboard actions, confirmed reset and early exit preserve the correct session lifecycle', async ({ page }) => {
  test.setTimeout(60000); await auditWorker(page); await start(page);
  await page.locator('main').focus(); await page.keyboard.press('1');
  await expect(page.getByRole('region', { name: 'Track workspace T01' })).toBeVisible();
  await page.locator('main').focus(); await page.keyboard.press('t');
  await expect(page.getByRole('button', { name: 'Tracked', exact: true })).toBeDisabled();
  await page.locator('main').focus(); await page.keyboard.press('o');
  await expect(page.getByRole('button', { name: /Request cooldown/ })).toBeDisabled();
  const before = (await lastView(page))!;
  expect(before.events.some(e => e.type === 'action' && e.data.action.kind === 'request_observation')).toBe(true);
  await page.getByRole('button', { name: 'Reset exercise', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Reset this exercise?' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused();
  await assertAccessible(page, 'reset confirmation');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Pause', exact: true })).toBeVisible();
  expect((await lastView(page))!.sessionId).toBe(before.sessionId);
  await page.getByRole('button', { name: 'Reset exercise', exact: true }).click();
  await page.getByRole('button', { name: 'Discard & reset', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Start exercise', exact: true })).toBeVisible();
  await expect(page.getByTestId('simulation-timer')).toHaveCount(0);
  await page.getByRole('button', { name: 'Start exercise', exact: true }).click();
  await expect.poll(async () => (await lastView(page))?.sessionId).not.toBe(before.sessionId);
  const restarted = (await lastView(page))!;
  expect(restarted.scenario.id).toBe(before.scenario.id); expect(restarted.scenario.seed).toBe(before.scenario.seed);
  expect(restarted.events[0].type).toBe('started'); expect(restarted.events[0].order).toBe(1);
  await page.getByRole('button', { name: 'End early', exact: true }).click();
  await page.getByRole('button', { name: 'End & review partial result', exact: true }).click();
  await expect(page.getByTestId('exercise-result')).toBeVisible();
  const partial = await finalRecord(page);
  expect(partial.status).toBe('aborted'); expect(partial.evaluation.comparable).toBe(false);
  expect(partial.elapsedSeconds).toBeLessThan(60);
  await expect(page.getByText('Partial · aborted', { exact: true })).toBeVisible();
  await expect(page.getByTestId('final-score')).toHaveText(partial.evaluation.score.toFixed(1));
});

test('leaving the console pauses and locks answers/profile without overwriting the active attempt', async ({ page }) => {
  test.setTimeout(60000); await auditWorker(page); await start(page);
  const active = (await lastView(page))!;
  await navigate(page, 'Individual progress');
  await expect(page.getByRole('button', { name: 'Return to console', exact: true })).toBeVisible();
  await expect.poll(async () => (await lastView(page))?.status).toBe('paused');
  const paused = (await lastView(page))!;
  await page.waitForTimeout(1100); expect((await lastView(page))!.elapsedSeconds).toBe(paused.elapsedSeconds);
  await expect(page.getByLabel('Active trainee profile')).toBeDisabled();
  await navigate(page, 'After-action review');
  await expect(page.getByText('Finish the exercise before reviewing answers', { exact: true })).toBeVisible();
  await expect(page.getByTestId('final-score')).toHaveCount(0);
  await navigate(page, 'Scenario Lab');
  await page.getByRole('button', { name: 'Return to active exercise', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Resume', exact: true })).toBeVisible();
  expect((await lastView(page))!.sessionId).toBe(active.sessionId);
  expect((await lastView(page))!.events.some(e => e.type === 'paused')).toBe(true);
  await page.getByRole('button', { name: 'End early', exact: true }).click();
  await page.getByRole('button', { name: 'End & review partial result', exact: true }).click();
  await expect(page.getByTestId('exercise-result')).toBeVisible();
});

test('a missing worker produces an explicit error, never a fictional exercise or score', async ({ page }) => {
  await page.addInitScript(() => { Object.defineProperty(window, 'Worker', { value: undefined, configurable: true }); });
  await page.goto('/#/lab'); await page.getByRole('button', { name: 'Review briefing', exact: true }).click();
  await page.getByRole('button', { name: 'Start exercise', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('cannot start a module Web Worker');
  await expect(page.getByTestId('simulation-timer')).toHaveCount(0);
  await expect(page.getByTestId('final-score')).toHaveCount(0);
});


test('a worker transport failure freezes the real snapshot and offers explicit discard/reset', async ({ page }) => {
  test.setTimeout(60000); await auditWorker(page); await start(page);
  const active = (await lastView(page))!;
  // Inject the browser's error event at the real Worker bridge, not replacement simulation data.
  await page.evaluate(() => window.__vigilWorker!.dispatchEvent(new ErrorEvent('error', { message: 'Injected test transport failure', cancelable: true })));
  await expect(page.getByRole('alert')).toContainText('last observation snapshot is retained');
  await expect(page.locator('.console-state')).toHaveText('DISCONNECTED');
  await expect(page.getByRole('button', { name: 'Pause', exact: true })).toBeDisabled();
  await expect(page.getByLabel('Clock', { exact: true })).toBeDisabled();
  const time = await page.getByTestId('simulation-timer').textContent();
  await page.waitForTimeout(1100);
  await expect(page.getByTestId('simulation-timer')).toHaveText(time!);
  await expect(page.getByTestId('final-score')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Dismiss simulation error' })).toHaveCount(0);
  expect((await lastView(page))!.sessionId).toBe(active.sessionId);
  expect(await page.evaluate(() => window.__vigilMessages.some(m => m.type === 'completed'))).toBe(false);
  await assertAccessible(page, 'disconnected observation snapshot');
  await navigate(page, 'After-action review');
  await expect(page.getByText('Finish the exercise before reviewing answers', { exact: true })).toBeVisible();
  await expect(page.locator('.active-exercise-banner')).toContainText('disconnected');
  await page.locator('.active-exercise-banner').getByRole('button', { name: 'Return to console', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('last observation snapshot is retained');
  await page.getByRole('button', { name: 'Reset exercise', exact: true }).click();
  await page.getByRole('button', { name: 'Discard & reset', exact: true }).click();
  await expect(page.getByText('Local worker ready', { exact: true })).toBeVisible();
  await expect(page.getByTestId('simulation-timer')).toHaveCount(0);
  await page.getByRole('button', { name: 'Start exercise', exact: true }).click();
  await expect.poll(async () => (await lastView(page))?.sessionId).not.toBe(active.sessionId);
  await expect(page.locator('.console-state')).toHaveText('RUNNING');
});
